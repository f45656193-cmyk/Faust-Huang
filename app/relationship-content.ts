export function applyRelationshipChoice(
  current: DeepRelationship,
  choiceId: string,
  week: number,
) {
  const next = {
    ...current,
    sharedMemories: [...current.sharedMemories],
    lastInteractionWeek: week,
    lastMeaningfulWeek: week,
    meaningfulInteractions: current.meaningfulInteractions + 1,
    familiarity: clamp(current.familiarity + 1.4),
    estrangement: clamp(current.estrangement - 2.4),
    careDebt: Math.max(0, current.careDebt - 1),
  };
  if (!next.sharedMemories.includes(choiceId))
    next.sharedMemories = [...next.sharedMemories, choiceId].slice(-12);
  if (choiceId.startsWith("rel-daily-")) {
    const parts = choiceId.split("-");
    const tone = parts[2];
    const personality = ["reserved", "warm", "competitive", "playful", "curious"].includes(parts[3])
      ? parts[3]
      : null;
    const innerConflict = ["abandonment", "burden", "achievement", "distance", "caretaking", "family"].includes(parts[4])
      ? parts[4]
      : null;
    if (tone === "care") {
      next.bond = clamp(next.bond + 2.8);
      next.trust = clamp(next.trust + 2.2);
      next.romance = clamp(next.romance + (next.route === "crush" || next.route === "dating" ? 1.6 : 0));
      next.conflict = clamp(next.conflict - 1.2);
      next.careDebt = Math.max(0, next.careDebt - 1.4);
      next.security = clamp(next.security + 2.2);
      next.reciprocity = clamp(next.reciprocity + (next.reciprocity < 50 ? 1.8 : 0.6));
    } else if (tone === "light") {
      next.bond = clamp(next.bond + 2.2);
      next.trust = clamp(next.trust + 0.8);
      next.romance = clamp(next.romance + (next.route === "crush" || next.route === "dating" ? 1.2 : 0));
      next.security = clamp(next.security + 0.7);
    } else if (tone === "honest") {
      next.bond = clamp(next.bond + 2.5);
      next.trust = clamp(next.trust + 3);
      next.romance = clamp(next.romance + (next.route === "crush" || next.route === "dating" ? 1.4 : 0));
      next.conflict = clamp(next.conflict - 1.4);
      next.security = clamp(next.security + 2.8);
      next.reciprocity = clamp(next.reciprocity + 1.2);
    } else if (tone === "practical") {
      next.bond = clamp(next.bond + 1.2);
      next.trust = clamp(next.trust + 1.8);
      next.security = clamp(next.security + 1.4);
    } else if (tone === "boundary") {
      next.bond = clamp(next.bond + 1.5);
      next.trust = clamp(next.trust + 2.5);
      next.conflict = clamp(next.conflict - 1.8);
      next.careDebt = Math.max(0, next.careDebt - 1.2);
      next.security = clamp(next.security + 2.4);
      next.reciprocity = clamp(next.reciprocity + 1.5);
    } else if (tone === "avoid") {
      next.bond = clamp(next.bond - 0.8);
      next.trust = clamp(next.trust - 0.7);
      next.tension = clamp(next.tension + 1.4);
      if (next.route === "dating") next.careDebt = clamp(next.careDebt + 1, 0, 20);
      next.security = clamp(next.security - 2.2);
      next.reciprocity = clamp(next.reciprocity - 1);
    } else if (tone === "hurt") {
      next.bond = clamp(next.bond - 2.2);
      next.trust = clamp(next.trust - 2.4);
      next.tension = clamp(next.tension + 2.5);
      next.conflict = clamp(next.conflict + 3.5);
      if (next.route === "dating") next.careDebt = clamp(next.careDebt + 1.5, 0, 20);
      next.security = clamp(next.security - 4);
      next.reciprocity = clamp(next.reciprocity - 2);
    }
    if (personality === "reserved" && (tone === "honest" || tone === "boundary"))
      next.trust = clamp(next.trust + 0.6);
    if (personality === "warm" && tone === "care") next.bond = clamp(next.bond + 0.5);
    if (personality === "warm" && tone === "hurt") next.conflict = clamp(next.conflict + 0.8);
    if (personality === "competitive" && tone === "practical") next.trust = clamp(next.trust + 0.6);
    if (personality === "competitive" && tone === "hurt") next.tension = clamp(next.tension + 0.8);
    if (personality === "playful" && tone === "light") next.bond = clamp(next.bond + 0.6);
    if (personality === "curious" && (tone === "honest" || tone === "practical"))
      next.trust = clamp(next.trust + 0.6);
    if (personality === "curious" && tone === "avoid") next.tension = clamp(next.tension + 0.5);
    if (innerConflict === "abandonment") {
      if (tone === "avoid" || tone === "hurt") next.bond = clamp(next.bond - 0.7);
      if (tone === "care" || tone === "honest") next.trust = clamp(next.trust + 0.4);
    }
    if (innerConflict === "burden" && tone === "hurt") next.trust = clamp(next.trust - 0.6);
    if (innerConflict === "achievement") {
      if (tone === "practical" || tone === "honest") next.trust = clamp(next.trust + 0.4);
      if (tone === "hurt") next.tension = clamp(next.tension + 0.5);
    }
    if (innerConflict === "distance" && tone === "boundary") next.trust = clamp(next.trust + 0.6);
    if (innerConflict === "caretaking" && (tone === "care" || tone === "honest"))
      next.trust = clamp(next.trust + 0.5);
    if (innerConflict === "family") {
      if (tone === "boundary" || tone === "care") next.trust = clamp(next.trust + 0.4);
      if (tone === "hurt") next.conflict = clamp(next.conflict + 0.5);
    }
    return next;
  }
  const positive = /warm|listen|share|heart|future|promise|honest|date-life|date-study|date-cheap|resist|repair-talk|repair-boundary|repair-apology|result-honest|friend-go|friend-call|friend-one-page/.test(choiceId);
  const practical = /practical|plan/.test(choiceId);
  const avoided = /avoid|dismiss|distance/.test(choiceId);
  if (positive) {
    next.bond = clamp(next.bond + 6);
    next.trust = clamp(next.trust + 5);
    next.romance = clamp(next.romance + (next.route === "crush" ? 5 : 1));
    next.conflict = clamp(next.conflict - 2);
    next.security = clamp(next.security + 2.5);
    next.reciprocity = clamp(next.reciprocity + 1.2);
  } else if (practical) {
    next.bond = clamp(next.bond + 4);
    next.trust = clamp(next.trust + 4);
    next.security = clamp(next.security + 1.5);
  } else if (avoided) {
    next.bond = clamp(next.bond - 2);
    next.trust = clamp(next.trust - 2);
    next.tension = clamp(next.tension + 4);
    next.security = clamp(next.security - 3);
    next.estrangement = clamp(next.estrangement + 2);
  }
  if (choiceId.startsWith("relationship-friend-")) {
    next.route = "friend";
    next.bond = clamp(next.bond + 10);
    next.trust = clamp(next.trust + 8);
    next.romance = 0;
  }
  if (choiceId.startsWith("relationship-crush-")) {
    next.route = "crush";
    next.romance = clamp(next.romance + 20);
    next.bond = clamp(next.bond + 7);
  }
  if (choiceId.startsWith("relationship-rivalry-")) {
    next.route = "rival";
    next.tension = clamp(next.tension + 18);
  }
  if (choiceId.startsWith("rel-date-") && !/^rel-date-(study|life|cheap)-/.test(choiceId)) {
    next.route = "dating";
    next.romance = clamp(next.romance + 24);
    next.bond = clamp(next.bond + 8);
    next.trust = clamp(next.trust + 6);
  }
  if (choiceId.startsWith("rel-rejected-")) {
    next.route = "strained";
    next.romance = clamp(next.romance - 14);
    next.conflict = clamp(next.conflict + 12);
  }
  if (choiceId.startsWith("rel-breakup-")) {
    next.route = "broken-up";
    next.breakupCount += 1;
    next.lastBreakupWeek = week;
    next.reunionUsed = false;
    next.secretContact = false;
    next.romance = clamp(next.romance - 24);
    next.conflict = clamp(next.conflict + 25);
  }
  if (choiceId.startsWith("rel-forced-breakup-")) {
    next.route = "broken-up";
    next.forcedBreakup = true;
    next.breakupCount += 1;
    next.lastBreakupWeek = week;
    next.reunionUsed = false;
    next.secretContact = false;
    next.romance = clamp(next.romance - 28);
    next.trust = clamp(next.trust - 15);
    next.conflict = clamp(next.conflict + 28);
  }
  if (choiceId.startsWith("rel-secret-contact-")) {
    next.secretContact = true;
    next.conflict = clamp(next.conflict + 12);
    next.careDebt = clamp(next.careDebt + 3, 0, 20);
  }
  if (choiceId.startsWith("rel-secret-confess-")) {
    next.secretContact = false;
    next.conflict = clamp(next.conflict + 12);
    next.careDebt = clamp(next.careDebt + 2, 0, 20);
  }
  if (choiceId.startsWith("rel-hide-") || choiceId.startsWith("rel-pause-")) {
    next.conflict = clamp(next.conflict + 8);
    next.careDebt = clamp(next.careDebt + 2, 0, 20);
  }
  return next;
}

export function settleRelationshipWeek(
  relation: DeepRelationship,
  interacted: boolean,
  week: number,
) {
  const next = { ...relation, sharedMemories: [...relation.sharedMemories] };
  if (interacted && relation.route === "neutral") {
    next.bond = clamp(next.bond + 2.8);
    next.trust = clamp(next.trust + 1.8);
    next.familiarity = clamp(next.familiarity + 1.4);
    next.security = clamp(next.security + 0.8);
    next.estrangement = clamp(next.estrangement - 1.5);
    next.meaningfulInteractions += 1;
    next.lastMeaningfulWeek = week;
    next.lastInteractionWeek = week;
    return next;
  }
  if (!(["dating", "friend", "crush"] as RelationshipRoute[]).includes(relation.route)) {
    const silentWeeks = week - next.lastInteractionWeek;
    if (!interacted && silentWeeks >= 7 && next.familiarity > 0) {
      const historyInertia = clamp(next.meaningfulInteractions / 18, 0, 0.55);
      next.familiarity = clamp(next.familiarity - (0.35 - historyInertia * 0.25));
      next.estrangement = clamp(next.estrangement + 0.25);
    }
    return next;
  }
  if (interacted) {
    next.bond = clamp(next.bond + (next.route === "dating" ? 0.45 : 0.3));
    next.trust = clamp(next.trust + 0.3);
    next.careDebt = Math.max(0, next.careDebt - 1.2);
    next.conflict = Math.max(0, next.conflict - 0.5);
    next.familiarity = clamp(next.familiarity + 0.65);
    next.security = clamp(next.security + 0.45);
    next.reciprocity = clamp(next.reciprocity + (next.reciprocity < 50 ? 0.5 : 0.15));
    next.estrangement = clamp(next.estrangement - 1.1);
    next.meaningfulInteractions += 1;
    next.lastMeaningfulWeek = week;
    next.lastInteractionWeek = week;
  } else if (next.route === "dating") {
    next.careDebt = clamp(next.careDebt + 0.7, 0, 20);
    const silentWeeks = week - next.lastInteractionWeek;
    const historyInertia = clamp(next.meaningfulInteractions / 22, 0, 0.5);
    if (silentWeeks >= 2) {
      next.bond = clamp(next.bond - Math.min(2.15, (0.5 + (silentWeeks - 2) * 0.2) * (1 - historyInertia)));
      next.trust = clamp(next.trust - Math.min(1.8, (0.32 + (silentWeeks - 2) * 0.18) * (1 - historyInertia * 0.7)));
      next.romance = clamp(next.romance - Math.min(1.25, 0.22 + (silentWeeks - 2) * 0.1));
      next.security = clamp(next.security - Math.min(2.4, 0.55 + (silentWeeks - 2) * 0.2));
      next.reciprocity = clamp(next.reciprocity - 0.35);
      next.estrangement = clamp(next.estrangement + Math.min(1.8, 0.45 + silentWeeks * 0.08));
    }
    if (silentWeeks >= 4) next.conflict = clamp(next.conflict + 1.1);
  } else if (!interacted) {
    const silentWeeks = week - next.lastInteractionWeek;
    const grace = next.route === "friend" ? 4 : 3;
    const historyInertia = clamp(next.meaningfulInteractions / 20, 0, 0.58);
    if (silentWeeks >= grace) {
      next.bond = clamp(next.bond - Math.min(next.route === "friend" ? 1.35 : 1.05, (0.24 + (silentWeeks - grace) * 0.12) * (1 - historyInertia)));
      next.familiarity = clamp(next.familiarity - Math.max(0.08, 0.32 - historyInertia * 0.35));
      next.security = clamp(next.security - Math.min(1.4, 0.25 + silentWeeks * 0.08));
      next.estrangement = clamp(next.estrangement + Math.min(1.2, 0.25 + silentWeeks * 0.06));
      if (next.route === "friend") next.trust = clamp(next.trust - Math.min(0.9, (0.14 + (silentWeeks - grace) * 0.08) * (1 - historyInertia * 0.6)));
      if (next.route === "crush") next.romance = clamp(next.romance - Math.min(0.8, 0.25 + silentWeeks * 0.04));
    }
    if (next.route === "friend" && silentWeeks >= 16 && next.bond < 18 && next.familiarity < 16)
      next.route = "neutral";
    if (next.route === "crush" && silentWeeks >= 12 && next.romance < 8)
      next.route = "neutral";
  }
  return next;
}

export type BreakupStyle = "peaceful" | "painful" | "forced";

export function breakupRelationship(
  relation: DeepRelationship,
  style: BreakupStyle,
  week: number,
) {
  const silentWeeks = Math.max(0, week - relation.lastInteractionWeek);
  const peaceful = style === "peaceful" || (style !== "forced" && silentWeeks >= 6);
  const next: DeepRelationship = {
    ...relation,
    route: "broken-up",
    romance: clamp(relation.romance - (peaceful ? 12 : 28)),
    bond: clamp(relation.bond - (peaceful ? 4 : 12)),
    trust: clamp(relation.trust - (style === "forced" ? 15 : peaceful ? 3 : 10)),
    conflict: clamp(relation.conflict + (style === "forced" ? 28 : peaceful ? 5 : 18)),
    breakupCount: relation.breakupCount + 1,
    forcedBreakup: style === "forced",
    secretContact: false,
    lastBreakupWeek: week,
  };
  return {
    relation: next,
    san: style === "forced" ? -12 : peaceful ? -2 : -8,
    mindset: style === "forced" ? -7 : peaceful ? -1 : -4,
    peaceful,
  };
}

export function attemptRelationshipReunion(
  relation: DeepRelationship,
  personality: RelationshipCandidate["personalityKey"],
  seed: string,
  week: number,
) {
  if (relation.route !== "broken-up" || relation.reunionUsed) return { outcome: "unavailable" as const, relation };
  const chance = clamp(
    0.18 + relation.bond * 0.004 + relation.trust * 0.003 - relation.conflict * 0.0035 +
      (personality === "warm" ? 0.08 : personality === "reserved" ? -0.03 : 0) +
      (relation.forcedBreakup ? -0.08 : 0),
    0.08,
    0.78,
  );
  const roll = (hashSeed(`${seed}-${week}-reunion`) % 10000) / 10000;
  if (roll < chance) {
    const secretContact = relation.forcedBreakup;
    return {
      outcome: secretContact ? "secret-contact" as const : "reunited" as const,
      relation: {
        ...relation,
        route: "dating" as const,
        reunionUsed: true,
        secretContact,
        romance: clamp(relation.romance + 15),
        bond: clamp(relation.bond + 7),
        trust: clamp(relation.trust + 5),
        conflict: clamp(relation.conflict - 8),
        lastInteractionWeek: week,
      },
    };
  }
  return { outcome: "ended" as const, relation: { ...relation, reunionUsed: true, secretContact: false } };
}

export function relationshipInterferenceOutcome(input: {
  coachFavor: number;
  familySupport: number;
  partnerTrust: number;
  regularScore: number;
  competitionScore: number;
  strictCoach: boolean;
  strictFamily: boolean;
  seed: string;
}) {
  const persuasion = input.partnerTrust * 0.22 + input.familySupport * 0.2 + input.coachFavor * 0.18 + input.regularScore * 0.16 + input.competitionScore * 0.18;
  const pressure = (input.strictCoach ? 18 : 7) + (input.strictFamily ? 18 : 6) + ((hashSeed(input.seed) % 1000) / 1000) * 20;
  return persuasion >= pressure ? "persuaded" as const : persuasion + 12 >= pressure ? "ultimatum" as const : "forced" as const;
}

export function relationshipLearningBoost(relationships: Record<string, DeepRelationship>) {
  const partner = Object.values(relationships).find((relation) => relation.route === "dating");
  if (!partner) return 0;
  if (partner.conflict >= 55 || partner.careDebt >= 8) return -0.04;
  return Math.min(0.06, 0.015 + partner.bond / 2000 + partner.trust / 2500);
}

export function relationshipWeeklyMoodEffect(
  relationships: Record<string, DeepRelationship>,
  week: number,
) {
  const partner = Object.values(relationships).find(
    (relation) => relation.route === "dating",
  );
  if (!partner) return 0;
  const silentWeeks = week - partner.lastInteractionWeek;
  if (partner.conflict >= 55 || partner.careDebt >= 8 || silentWeeks >= 7)
    return -1.2;
  if (silentWeeks >= 4) return -0.6;
  if (silentWeeks <= 1 && partner.bond >= 55) return 0.45;
  return 0.1;
}
