function personalizeCommonMainline(
  event: GameEvent,
  candidate: RelationshipCandidate,
  chapter: CommonMainlineChapter,
) {
  const name = candidate.rival.name;
  const fillName = (value: string) => value.replaceAll("{NPC}", name);
  const conflict = candidate.innerConflictKey ?? "distance";
  const turnTitles = turnChoiceTitles[candidate.personalityKey];
  const turnResults = commonTurnChoiceResults[candidate.personalityKey];
  const nightResults = nightChoiceResults[candidate.personalityKey];
  const choiceTitle = (choice: GameEvent["choices"][number], index: number) => {
    if (chapter === "night") return nightChoiceTitles[candidate.personalityKey][index] ?? choice.title;
    if (choice.id.startsWith("relationship-friend-")) return turnTitles.friend;
    if (choice.id.startsWith("relationship-crush-")) return turnTitles.crush;
    if (choice.id.startsWith("relationship-rivalry-")) return turnTitles.rivalry;
    if (choice.id.startsWith("rel-distance-")) return turnTitles.distance;
    return choice.title;
  };
  const turnResult = (choice: GameEvent["choices"][number]) => {
    if (chapter === "night") {
      const index = event.choices.indexOf(choice);
      return nightResults[index] ?? choice.result;
    }
    if (choice.id.startsWith("relationship-friend-")) return turnResults.friend;
    if (choice.id.startsWith("relationship-crush-")) return turnResults.crush;
    if (choice.id.startsWith("relationship-rivalry-")) return turnResults.rivalry;
    if (choice.id.startsWith("rel-distance-")) return turnResults.distance;
    return choice.result;
  };
  return {
    ...event,
    title: fillName(commonChapterTitles[chapter][candidate.personalityKey]),
    body: [
      fillName(commonChapterOpenings[chapter][candidate.personalityKey]),
      fillName(commonConflictLines[chapter][conflict]),
      ...event.body.slice(1),
    ],
    choices: event.choices.map((choice, index) => ({
      ...choice,
      title: choiceTitle(choice, index),
      result: fillName(turnResult(choice)),
    })),
  } satisfies GameEvent;
}

