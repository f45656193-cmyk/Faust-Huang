function nodeEffects(config: ChainConfig, index: number, active: boolean): GameEffect {
  const base = active ? config.activeEffects : config.passiveEffects;
  const effects: GameEffect = { ...base };
  if (!active && config.id === "slack" && index >= 6) {
    effects.san = index >= 8 ? -2 : 1;
    effects.mindset = index >= 8 ? -3 : -1;
    effects.coachFavor = index >= 8 ? -5 : -2;
    effects.tags = index >= 8 ? ["被教练正式约谈"] : ["拖延开始影响训练"];
  }
  if (!active && config.id === "isolation") {
    effects.peerFavor = index >= 5 ? -3 : -1.5;
    effects.san = index >= 6 ? -4 : -2;
    effects.mindset = index >= 6 ? -2 : -1;
    if (index >= 6) effects.tags = ["被竞赛队边缘化"];
  }
  if (active && config.id === "isolation" && index >= 4) {
    effects.peerFavor = 4;
    effects.social = 2;
    effects.tags = index >= 8 ? ["开始修复队内关系"] : ["主动沟通队内矛盾"];
  }
  if (!active && config.id === "coach" && index >= 4) {
    effects.coachFavor = index >= 7 ? -4 : -2;
    effects.mindset = -1;
    effects.tags = index >= 7 ? ["教练认为你执行力不足"] : ["过度占用教练时间"];
  }
  if (!active && config.id === "school-exam") {
    effects.academics = index >= 5 ? -2 : -0.8;
    effects.san = index >= 7 ? -2 : 0.5;
  }
  return effects;
}

function chainEvent(config: ChainConfig, index: number): GameEvent {
  const step = index + 1;
  const previousTag = `chain:${config.id}:${step - 1}:done`;
  const currentTag = `chain:${config.id}:${step}:done`;
  const scene = sceneLibraries[config.id]?.[index] ?? config.premise;
  const decisions = choiceLibraries[config.id]?.[index];
  const activeTitle = decisions?.[0] ?? config.activeChoice;
  const passiveTitle = decisions?.[1] ?? config.passiveChoice;
  const results = resultLibraries[config.id]?.[index];
  const activeEffects = nodeEffects(config, index, true);
  const passiveEffects = nodeEffects(config, index, false);
  return {
    id: `chain-${config.id}-${String(step).padStart(2, "0")}`,
    phase: "weekly",
    label: `${config.label} · ${step}/10`,
    title: config.titles[index],
    body: [scene],
    inspiration: "原创",
    trigger: {
      earliestWeek: config.earliestWeek + index,
      latestWeek: 104,
      requiredTags: index === 0 ? undefined : [previousTag],
      requiredActionCounts:
        index === 0 && config.actionKey
          ? { [config.actionKey]: config.actionThreshold ?? 1 }
          : undefined,
      maxSan: index === 0 ? config.maxSan : undefined,
      maxPeerFavor: index === 0 ? config.maxPeerFavor : undefined,
      minRegularNeglectWeeks:
        index === 0 ? config.minRegularNeglectWeeks : undefined,
      probability: 0.72,
    },
    choices: [
      {
        id: `${config.id}-${step}-active`,
        title: activeTitle,
        preview: "立即执行 · 承担短期成本 · 改变后续关系或习惯",
        result:
          results?.[0] ??
          `你选择了“${activeTitle}”。事情没有立刻变好，但至少不再完全按原来的惯性发展。`,
        effects: {
          ...activeEffects,
          tags: [...(activeEffects.tags ?? []), currentTag],
        },
      },
      {
        id: `${config.id}-${step}-passive`,
        title: passiveTitle,
        preview: "回避眼前冲突 · 后果会进入后续节点",
        result:
          results?.[1] ??
          `你选择了“${passiveTitle}”。眼前的尴尬结束了，未处理的问题却被带进了下一周。`,
        effects: {
          ...passiveEffects,
          tags: [...(passiveEffects.tags ?? []), currentTag],
        },
      },
    ],
  };
}

export const linkedWeeklyEvents: GameEvent[] = chains.flatMap((config) =>
  config.titles.map((_, index) => chainEvent(config, index)),
);

export const linkedEventCount = linkedWeeklyEvents.length;
