function personalizeCrushMainline(
  event: GameEvent,
  candidate: RelationshipCandidate,
  chapter: CrushMainlineChapter,
) {
  const name = candidate.rival.name;
  const fillName = (value: string) => value.replaceAll("{NPC}", name);
  const conflict = candidate.innerConflictKey ?? "distance";
  const titles = crushChoiceTitles[chapter][candidate.personalityKey];
  const results = crushChoiceResults[chapter][candidate.personalityKey];
  return {
    ...event,
    title: fillName(crushChapterTitles[chapter][candidate.personalityKey]),
    body: [
      fillName(crushChapterOpenings[chapter][candidate.personalityKey]),
      fillName(crushConflictLines[chapter][conflict]),
      ...event.body.slice(1),
    ],
    choices: event.choices.map((choice, index) => ({
      ...choice,
      title: titles[index] ?? choice.title,
      result: fillName(results[index] ?? choice.result),
    })),
  } satisfies GameEvent;
}

