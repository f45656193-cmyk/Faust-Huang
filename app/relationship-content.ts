function personalizeFriendMainline(
  event: GameEvent,
  candidate: RelationshipCandidate,
  chapter: FriendMainlineChapter,
) {
  const name = candidate.rival.name;
  const fillName = (value: string) => value.replaceAll("{NPC}", name);
  const conflict = candidate.innerConflictKey ?? "distance";
  const titles = friendChoiceTitles[chapter][candidate.personalityKey];
  const results = friendChoiceResults[chapter][candidate.personalityKey];
  return {
    ...event,
    title: fillName(friendChapterTitles[chapter][candidate.personalityKey]),
    body: [
      fillName(friendChapterOpenings[chapter][candidate.personalityKey]),
      fillName(friendConflictLines[chapter][conflict]),
      ...event.body.slice(1),
    ],
    choices: event.choices.map((choice, index) => ({
      ...choice,
      title: titles[index] ?? choice.title,
      result: fillName(results[index] ?? choice.result),
    })),
  } satisfies GameEvent;
}

