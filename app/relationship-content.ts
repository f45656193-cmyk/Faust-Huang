const clamp = (value: number, min = 0, max = 100) =>
  Math.max(min, Math.min(max, value));

function hashSeed(value: string) {
  let hash = 2166136261;
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return Math.abs(hash >>> 0);
}

export function defaultRelationship(seed = "", rivalId = ""): DeepRelationship {
  return {
    bond: 4 + (hashSeed(`${seed}-${rivalId}-bond`) % 8),
    tension: hashSeed(`${seed}-${rivalId}-tension`) % 5,
    romance: 0,
    trust: 2,
    familiarity: 3 + (hashSeed(`${seed}-${rivalId}-familiarity`) % 6),
    security: 12,
    reciprocity: 50,
    estrangement: 0,
    meaningfulInteractions: 0,
    lastMeaningfulWeek: 0,
    sharedMemories: [],
    careDebt: 0,
    conflict: 0,
    route: "neutral",
    lastInteractionWeek: 0,
    breakupCount: 0,
    reunionUsed: false,
    forcedBreakup: false,
    secretContact: false,
    lastBreakupWeek: 0,
  };
}

export function normalizeRelationship(
  value: Partial<DeepRelationship> | undefined,
  seed = "",
  rivalId = "",
): DeepRelationship {
  const normalized = { ...defaultRelationship(seed, rivalId), ...(value ?? {}) };
  return {
    ...normalized,
    sharedMemories: [...(value?.sharedMemories ?? [])],
  };
}

export function relationshipRouteLabel(relation: DeepRelationship) {
  if (relation.route === "dating") {
    if (relation.secretContact) return "藕断丝连 · 未公开";
    if (relation.breakupCount > 0) return relation.conflict >= 45 ? "复合后的恋人 · 关系紧张" : "复合后的恋人";
    return relation.conflict >= 45 ? "恋人 · 关系紧张" : "恋人";
  }
  if (relation.route === "broken-up") return "已经分手";
  if (relation.route === "friend") return relation.bond >= 62 ? "挚友" : "好友";
  if (relation.route === "rival") return "宿敌";
  if (relation.route === "strained") return "逐渐疏远";
  if (relation.route === "crush") return relation.romance >= 32 ? "朦胧心意" : "似乎有些在意";
  if (relation.tension >= 35) return "竞争升温";
  if (relation.bond >= 20) return "逐渐熟悉";
  return "普通队友";
}

