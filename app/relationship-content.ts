function personalizeDatingMainline(
  event: GameEvent,
  candidate: RelationshipCandidate,
  chapter: DatingMainlineChapter,
) {
  const name = candidate.rival.name;
  const fillName = (value: string) => value.replaceAll("{NPC}", name);
  const titleVariants = datingChoiceTitles[chapter][candidate.personalityKey] ?? [];
  const lateResults = chapter === "repair" || chapter === "different-results"
    ? datingLateChoiceResults[chapter][candidate.personalityKey]
    : null;
  const earlyResults = chapter === "ordinary-date" || chapter === "secret-discovered" || chapter === "reunion-after"
    ? datingEarlyChoiceResults[chapter][candidate.personalityKey]
    : null;
  const conflict = candidate.innerConflictKey ?? "distance";
  const choiceTitle = (choice: GameEvent["choices"][number], index: number) => {
    if (chapter === "interference" && choice.id.includes("rel-forced-breakup-")) {
      return forcedInterferenceChoiceTitles[candidate.personalityKey].breakup;
    }
    if (chapter === "interference" && choice.id.includes("rel-secret-contact-")) {
      return forcedInterferenceChoiceTitles[candidate.personalityKey].secret;
    }
    return titleVariants[index] ?? choice.title;
  };
  const interferenceOutcomeKey = (choice: GameEvent["choices"][number]): InterferenceOutcomeKey | null => {
    if (choice.id.includes("rel-forced-breakup-")) return "forced-breakup";
    if (choice.id.includes("rel-secret-contact-")) return "secret-contact";
    if (choice.id.includes("rel-resist-")) return "resist";
    if (choice.id.includes("rel-hide-")) return "hide";
    if (choice.id.includes("rel-pause-")) return "pause";
    if (choice.id.includes("rel-breakup-")) return "breakup";
    return null;
  };
  return {
    ...event,
    title: fillName(datingChapterTitles[chapter][candidate.personalityKey]),
    body: [
      fillName(datingChapterOpenings[chapter][candidate.personalityKey]),
      fillName(innerConflictLines[chapter][conflict]),
      ...event.body.slice(1),
    ],
    choices: event.choices.map((choice, index) => {
      const interferenceKey = chapter === "interference" ? interferenceOutcomeKey(choice) : null;
      return {
        ...choice,
        title: choiceTitle(choice, index),
        result: fillName(
          (interferenceKey ? interferenceChoiceResults[candidate.personalityKey][interferenceKey] : null) ??
            lateResults?.[index] ??
            earlyResults?.[index] ??
            choice.result,
        ),
      };
    }),
  } satisfies GameEvent;
}

